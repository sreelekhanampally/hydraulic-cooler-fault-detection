# 1. Read the data (slide 2) -----------------------------------------------
cycles <- read.csv("R/data/cycle_features_R.csv")
profiles <- read.csv("R/data/matched_profiles_R.csv")
results <- readRDS("R/results/analysis_R.rds")
features <- CORE
nrow(cycles)                         # 2,205 recorded cycles
sum(cycles$unstable == 0)            # 1,449 stable cycles
table(profiles$cooler)               # 48 matched profiles per condition
head(profiles[, c("cooler", features)])

# 2. Mean vector (slide 3) -------------------------------------------------
full <- profiles[profiles$cooler == 100, features]
reduced <- profiles[profiles$cooler == 20, features]
near <- profiles[profiles$cooler == 3, features]
means <- rbind(Full = colMeans(full), Reduced = colMeans(reduced),
               Near_failure = colMeans(near))
round(means, 4)

# 3. Covariance and correlation (slide 4) ----------------------------------
cov(near)                            # Units affect these values.
round(cor(near), 3)                  # Correlation is between -1 and +1.

# 4. Generalized variance (slide 5) ----------------------------------------
# Put every condition on the SAME scale before comparing determinants.
common_scale <- fit_scaler(profiles[, features])
z <- apply_scaler(profiles[, features], common_scale)
groups <- lapply(CLASS_ORDER, function(k) z[profiles$cooler == k, ])
spread <- sapply(groups, function(x) det(cov(x))^(1 / 6))
names(spread) <- c("Full", "Reduced", "Near failure")
spread
spread[3] / spread[1]                # About 6.1 times larger near failure.

# 5. Distribution checks (slide 6) ----------------------------------------
# Our function implements Mardia's joint skewness and kurtosis formulas.
mardia_statistics(groups[[3]])
# The saved p-values come from 999 normal samples generated by R.
results$distribution_checks$groups[[3]][c("skew_p_mc", "kurtosis_p_mc")]

# 6. Maximum likelihood estimation (slide 7) -------------------------------
mean_ML <- colMeans(groups[[1]])
n <- nrow(groups[[1]])
covariance_ML <- cov(groups[[1]]) * (n - 1) / n
mean_ML
covariance_ML
# optim() also fits the two-feature example. Both answers agree.
MLE_check <- numerical_mle_R(groups[[1]])
MLE_check[c("analytic_loglik", "numeric_loglik", "optimizer_success")]

# 7. MANOVA (slide 8) ------------------------------------------------------
# Compare six responses together, allowing each setting its own baseline.
fit <- manova(z ~ factor(setting) + factor(cooler), data = profiles)
# Read the factor(cooler) row for the condition comparison.
summary(fit, test = "Wilks")
summary(fit, test = "Roy")

# 8. Paired Hotelling T2 (slide 9) -----------------------------------------
# Match the SAME settings before subtracting the two condition profiles.
pair <- merge(profiles[profiles$cooler == 100, c("setting", features)],
              profiles[profiles$cooler == 20, c("setting", features)],
              by = "setting", suffixes = c("_full", "_reduced"))
differences <- as.matrix(pair[, paste0(features, "_reduced")]) -
               as.matrix(pair[, paste0(features, "_full")])
paired_hotelling(differences)[c("T2", "F", "p_iid")]
# Adjust the three planned comparisons together.
p_values <- sapply(results$hotelling, function(x) x$p_iid)
p.adjust(p_values, method = "holm")

# 9. Covariance equality (slide 10) ----------------------------------------
box_m(groups)[c("M", "chi2", "df", "p_iid")]
covariance_lrt(groups)               # A separate likelihood-ratio check.

# 10. Partial correlation (slide 11) ---------------------------------------
# Remove recorded group differences, then correlate what remains.
controls <- model.matrix(~ factor(cooler) + factor(valve) +
                         factor(pump) + factor(accumulator), data = profiles)
residuals <- lm.fit(controls, z)$residuals
cor(z)[1, 6]                        # Temperature-vibration before adjustment.
cor(residuals)[1, 6]                # Temperature-vibration after adjustment.

# 11. Simulation and resampling (slide 12) ---------------------------------
# The full workflow refits MANOVA on 999 simulated/resampled datasets.
sapply(results$manova$resampling, function(x) x$p_mc)
# Repeatedly sample complete test settings to check the observed score.
results$holdout_block_bootstrap$TS2_unavailable[c("lower", "upper")]
# [1, 1] describes this perfect test sample. It does not guarantee future accuracy.

# 12. Fit and test our selected model (slides 12 and 13) ---------------------
# The full workflow compared candidates using only development settings.
results$selected_model               # "shared": one common covariance matrix.
train <- cycles[cycles$cycle_id %in% results$development_cycles, ]
test <- cycles[cycles$cycle_id %in% results$test_cycles, ]
nrow(train)                          # 1,089 training cycles.
nrow(test)                           # 360 separate test cycles.
scaler <- fit_scaler(train[, features])
z_train <- apply_scaler(train[, features], scaler)
z_test <- apply_scaler(test[, features], scaler)
model <- fit_gaussian(z_train, train$cooler, kind = "shared", alpha = 0)
probability <- predict_gaussian(model, z_test)
predicted <- CLASS_ORDER[max.col(probability, ties.method = "first")]
table(Recorded = test$cooler, Predicted = predicted)
mean(predicted == test$cooler)        # 1 = 100% in this stable test sample.

# Remove both TS2 measurements and use the remaining four features.
probability_without_TS2 <- predict_gaussian(model, z_test, available = 3:6)
predicted_without_TS2 <- CLASS_ORDER[max.col(probability_without_TS2,
                                            ties.method = "first")]
table(Recorded = test$cooler, Predicted = predicted_without_TS2)

# 13. Change a reading (slide 13) ------------------------------------------
saved_model <- readRDS("R/models/trained_gaussian_model.rds")
example <- test[test$cooler == 3, ][1, ]
predict_frame_R(saved_model, example)
example$TS2_mean <- example$TS2_mean - 8
predict_frame_R(saved_model, example) # Artificial reading change, not a new experiment.
predict_frame_R(saved_model, example, without_temperature = TRUE)

